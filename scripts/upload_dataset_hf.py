"""Publish the phase0_v4 synthetic dataset to the HuggingFace Hub as a dataset repo.

Uploads only the 12 grid groups (g00..g11) - the rendered frames, the merged
multi-instance COCO, and a dataset card. Test/scratch groups are excluded.

    uv run python scripts/upload_dataset_hf.py --repo-id <user>/<name> [--private]

Requires `huggingface-hub` and a logged-in token (`hf auth login` or HF_TOKEN).
"""

from __future__ import annotations

import argparse
from pathlib import Path

from huggingface_hub import HfApi

_REPO = Path(__file__).resolve().parent.parent  # ue5-vehicle-synth/
CAPTURES = _REPO / "captures" / "phase0_v4"

CARD = """---
license: mit
task_categories:
  - keypoint-detection
tags:
  - synthetic
  - unreal-engine-5
  - city-sample
  - vehicle
  - keypoints
  - sim-to-real
  - autonomous-driving
pretty_name: City Sample Vehicle Keypoints (24-point, synthetic)
size_categories:
  - 1K<n<10K
---

# City Sample Vehicle Keypoints (24-point, synthetic)

A synthetic vehicle-keypoint dataset rendered inside Epic's **City Sample**
("Matrix Awakens") with Unreal Engine 5.6 and Movie Render Queue. Vehicles are
placed on the real ZoneGraph road network, and every visible vehicle is labelled
with a 24-point anatomical keypoint schema plus a mesh-bounds bounding box.

Generated by the open pipeline at
[**kiselyovd/ue5-vehicle-synth**](https://github.com/kiselyovd/ue5-vehicle-synth)
(full method, code, and engineering write-up in the repo wiki).

## Contents

- **{n_img} frames** at 1280x720 PNG, across 36 capture groups: \
4 city-street venues x 3 lighting presets (clear day, golden hour, overcast) x \
3 hero vehicle rigs (sedan, minivan, pickup). Each scene is additionally \
populated with parked car/van types drawn at random from the City Sample \
fleet, so labelled instances cover more body shapes than the three hero rigs.
- **{n_ann} annotations** (multi-instance: the rig vehicle plus every visible \
labelled city vehicle per frame, ~5.7/frame), `annotations/coco.json` in COCO \
keypoint format.
- Per-point visibility split: 55.9% visible (v=2), 34.2% occluded (v=1), \
9.9% off-frame/absent (v=0) - the capture is deliberately biased toward hard \
framing and occlusion.
- `captures_all.jsonl` - the raw per-frame records the COCO is built from.

## The 24-point schema

Points 0-13 are the **CarFusion canonical order** (4 wheels, 4 head/tail lights,
exhaust, 4 roof corners, body center) for backward compatibility with 14-point
models. Points 14-23 extend it: 2 side mirrors, 4 bumper corners, 4 window-base
corners. Per-point visibility follows CarFusion: `2` visible, `1` self-occluded,
`0` off-frame.

Every keypoint location is derived geometrically from the vehicle's own mesh \
data - wheels from the skeletal wheel bones, roof corners from the body vertex \
cloud's roofline plateau, head/tail lights and mirrors from the centroids of \
the mesh sections bound to the light/mirror materials - so per-type configs \
are exact to each body shape (a van's high tail lights, a pickup's cab-only \
roof), not a scaled sedan template.

## Intended use

Synthetic pre-training / augmentation for real-world vehicle-keypoint models
(sim-to-real). It is a **Phase-0 vertical slice**: the focus is the pipeline and
a proof-of-concept sample, not a final large-scale corpus.

## Used by

- [Synthetic 24-pt model](https://huggingface.co/kiselyovd/citysample-vehicle-keypoints-24pt) -
  a YOLO-pose model trained entirely on this synthetic data (the in-domain model).
- [Real CarFusion model](https://huggingface.co/kiselyovd/vehicle-keypoints) -
  the real-world baseline the sim-to-real study compares against.

## Honest status

This slice was built to test a kill switch: *does synthetic pre-training improve
a real-world model?* Results are reported transparently in the source repo - a
narrow single-city slice is a hard case for sim-to-real transfer, and negative
or marginal results are documented rather than hidden. Use it as a research
artifact and a pipeline demonstration.

## License & provenance

Frames are non-interactive media rendered with Unreal Engine from City Sample.
Under the UE EULA, such rendered images are freely distributable; no Epic asset
files are included - only rendered PNGs and JSON annotations. The MIT license
covers these frames and annotations, not Epic's underlying assets. See the
[EULA analysis](https://github.com/kiselyovd/ue5-vehicle-synth/blob/main/docs/legal/CITY_SAMPLE_EULA_REVIEW.md).
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo-id", default="kiselyovd/citysample-vehicle-keypoints-24pt")
    ap.add_argument("--private", action="store_true")
    ap.add_argument("--dry-run", action="store_true", help="build card + list files, no upload")
    args = ap.parse_args()

    import json

    coco = json.loads((CAPTURES / "annotations" / "coco.json").read_text(encoding="utf-8"))
    card = CARD.format(n_img=f"{len(coco['images']):,}", n_ann=f"{len(coco['annotations']):,}")
    (CAPTURES / "README.md").write_text(card, encoding="utf-8")
    print(f"card written ({len(coco['images'])} images / {len(coco['annotations'])} anns)")

    # Only the 36 venue groups + annotations + jsonl + card.
    allow = [
        "downtown_*/rgb/*.png",
        "residential_*/rgb/*.png",
        "intersection_*/rgb/*.png",
        "arterial_*/rgb/*.png",
        "annotations/coco.json",
        "captures_all.jsonl",
        "README.md",
    ]
    # The g00..g11 groups on the Hub are the superseded early capture; remove them.
    delete = ["g??_v?_*/**"]
    if args.dry_run:
        api = HfApi()
        n = sum(1 for p in allow[:4] for _ in CAPTURES.glob(p))
        print(f"DRY RUN: would upload {n} PNGs + COCO + jsonl + card to {args.repo_id}")
        return

    api = HfApi()
    api.create_repo(args.repo_id, repo_type="dataset", private=args.private, exist_ok=True)
    api.upload_folder(
        folder_path=str(CAPTURES),
        repo_id=args.repo_id,
        repo_type="dataset",
        allow_patterns=allow,
        delete_patterns=delete,
        commit_message="Re-capture: 2510 frames, 36 groups, mesh-derived precise 24-pt configs",
    )
    print(f"uploaded -> https://huggingface.co/datasets/{args.repo_id}")


if __name__ == "__main__":
    main()
